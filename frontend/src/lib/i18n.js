const dicts = {
  en,
  hi: { ...en, ...hi },
  or: { ...en, ...or_ },
  bn: { ...en, ...bn },
  gu: { ...en, ...gu },
  ta: { ...en, ...ta },
  te: { ...en, ...te },
};

const I18nContext = createContext({ lang: "en", t: (k) => k, catName: (s, f) => f });

export function I18nProvider({ children }) {
  const { lang } = useParams();
  const code = LOCALE_CODES.includes(lang) ? lang : "en";
  const value = useMemo(() => {
    const dict = dicts[code] || en;
    const t = (k) => dict[k] ?? en[k] ?? k;
    // Category names come from the catalogue; translate by slug, fall back to the stored name.
    const catName = (slug, fallback) => dict[`cat.${slug}`] ?? fallback ?? en[`cat.${slug}`] ?? slug;
    return { lang: code, t, catName };
  }, [code]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
